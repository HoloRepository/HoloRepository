"""The shared label list (labels.json): ids and names that stay the same for every model.

Generated by tools/make_labels.py from NV-Segment-CT's metadata.json. Model code uses ids; add-ons and
post-processing ask by name, so they work with any base model.
"""

import json
from collections.abc import Iterable
from pathlib import Path
from typing import NamedTuple


class Label(NamedTuple):
    name: str
    parent: int | None


def _load() -> tuple[dict[int, Label], dict[str, int]]:
    raw = json.loads((Path(__file__).parent / "labels.json").read_text())
    by_id = {int(i): Label(entry["name"], entry["parent"]) for i, entry in raw.items()}  # JSON keys are strings
    by_name = {label.name: i for i, label in by_id.items()}
    if len(by_name) != len(by_id):
        raise ValueError("labels.json has duplicate names")  # names must be unique to work as a key
    return by_id, by_name


BY_ID, BY_NAME = _load()  # once, at import


def id_of(name: str) -> int:
    if name not in BY_NAME:
        raise KeyError(f"Unknown label name '{name}'")  # a typo fails at startup, not silently
    return BY_NAME[name]


def name_of(label_id: int) -> str:
    if label_id not in BY_ID:
        raise KeyError(f"Unknown label id {label_id}")
    return BY_ID[label_id].name


def table_for(ids: Iterable[int]) -> dict[str, dict[str, str | int | None]]:
    """Per-job labels.json for meshing: {"<id>": {"name", "parent"}} for the ids present in a label map.

    Background (0) is skipped, so the ids can come straight from np.unique(label_map).
    """
    present = sorted({int(i) for i in ids} - {0})
    return {str(i): {"name": name_of(i), "parent": BY_ID[i].parent} for i in present}
